"""Schema-level checks: migrations stay in step with the models, and the
indexes do the jobs explorer/docs/schema.md claims they do."""
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text

from tests.conftest import alembic_config


def test_models_match_migrations(engine):
    try:
        command.check(alembic_config())
    except AutogenerateDiffsDetected as diff:  # pragma: no cover - failure path
        raise AssertionError(f"Models and migrations have drifted:\n{diff}") from diff


def test_migration_round_trip(engine):
    config = alembic_config()
    command.downgrade(config, "base")
    command.upgrade(config, "head")


def _plan(conn, sql: str) -> str:
    # With only 414 rows Postgres would rightly choose a sequential scan, so
    # disable that option to check which index is *available* to the query.
    conn.execute(text("SET LOCAL enable_seqscan = off"))
    return "\n".join(row[0] for row in conn.execute(text(f"EXPLAIN {sql}")))


def test_airport_range_query_uses_primary_key(loaded_db):
    with loaded_db.begin() as conn:
        plan = _plan(
            conn,
            "SELECT * FROM monthly_stats WHERE airport_code = 'BFS' "
            "AND period_start BETWEEN '2019-01-01' AND '2019-12-01'",
        )
    assert "pk_monthly_stats" in plan


def test_cross_airport_period_query_uses_period_index(loaded_db):
    with loaded_db.begin() as conn:
        plan = _plan(conn, "SELECT * FROM monthly_stats WHERE period_start >= '2026-01-01'")
    assert "ix_monthly_stats_period_start" in plan


def test_latest_forecast_run_uses_unique_constraint_index(loaded_db):
    with loaded_db.begin() as conn:
        plan = _plan(
            conn,
            "SELECT * FROM forecast_runs WHERE model_name = 'ETS' ORDER BY trained_through DESC LIMIT 1",
        )
    assert "uq_forecast_runs_model_trained_through" in plan
